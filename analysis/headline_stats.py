#!/usr/bin/env python3
"""Single source for every number quoted in the findings prose. Writes docs/findings/numbers.md.

Definitions (used consistently):
  all         every district in the 2026-27 UFB with a benefits line (panel rows)
  comparable  operating districts with a revised 2025-26 baseline and a row in the NJDOE formula-aid file
              (excludes non-operating districts, service commissions, special-services districts)

    .venv/bin/python analysis/headline_stats.py
"""
import csv
import glob
import statistics
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def med(xs):
    xs = [x for x in xs if x is not None]
    return (statistics.median(xs), len(xs)) if xs else (None, 0)


def ufb_benefit_budgets():
    """{budget_year_file: {district: (orig_budget_this_year)}} using amount_3 of each file (that year's adopted budget)."""
    out = {}
    for fpath in sorted(glob.glob(str(RAW / "ufb" / "*" / "approp*.csv"))):
        yr = Path(fpath).parent.name
        with open(fpath, encoding="latin-1") as fh:
            for r in csv.DictReader(fh):
                if r["line_no"].strip() == "71260":
                    out.setdefault(yr, {})[r["district_id"]] = f(r["amount_3"]) or 0
    return out


def main():
    rows = list(csv.DictReader(open(ROOT / "data" / "processed" / "district_panel.csv")))
    comp = [r for r in rows if r["comparable"] == "True"]
    L = ["# Numbers used in the findings", "",
         "_Generated by `analysis/headline_stats.py`. Every figure quoted in `docs/findings/*.md` should come from this page. "
         "\"Comparable\" = operating districts with a revised 2025-26 baseline and a row in the NJDOE formula-aid file._", ""]

    def block(title, items):
        L.extend([f"## {title}", ""] + [f"- {k}: **{v}**" for k, v in items] + [""])

    ben = lambda rs, c: sum(f(r[c]) or 0 for r in rs)
    b26, b27 = ben(comp, "benefits_budget_2526"), ben(comp, "benefits_budget_2627")
    o26, o27 = ben(comp, "other_gce_budget_2526"), ben(comp, "other_gce_budget_2627")
    aid = ben(comp, "state_aid_change_dollars")
    inc = [r for r in comp if r["benefits_line_incomplete"] != "True" and (f(r["benefits_change_pct"]) or 0) > -10]
    bi26, bi27 = ben(inc, "benefits_budget_2526"), ben(inc, "benefits_budget_2627")
    ab26, ab27 = ben(rows, "benefits_budget_2526"), ben(rows, "benefits_budget_2627")
    block("Districts", [("All districts in panel", len(rows)), ("Comparable districts", len(comp)),
                        ("Excluded as non-comparable", len(rows) - len(comp))])
    block("Benefits vs. everything else (comparable districts, 2025-26 revised → 2026-27 budget)", [
        ("Employee benefits", f"${b26/1e6:,.0f}M → ${b27/1e6:,.0f}M ({(b27/b26-1)*100:+.1f}%, {(b27-b26)/1e6:+,.0f}M)"),
        ("All other general current expense", f"${o26/1e6:,.0f}M → ${o27/1e6:,.0f}M ({(o27/o26-1)*100:+.1f}%)"),
        ("Median district: benefits change", f"{med([f(r['benefits_change_pct']) for r in comp])[0]:+.1f}% (n={med([f(r['benefits_change_pct']) for r in comp])[1]})"),
        ("Median district: all other spending change", f"{med([(f(r['other_gce_budget_2627'])/f(r['other_gce_budget_2526'])-1)*100 for r in comp if f(r['other_gce_budget_2526'])])[0]:+.1f}%"),
        ("All districts (incl. non-comparable)", f"${ab26/1e6:,.0f}M → ${ab27/1e6:,.0f}M ({(ab27/ab26-1)*100:+.1f}%)"),
        ("Excluding districts whose benefits line is incomplete or fell >10% (accounting moves)",
         f"${bi26/1e6:,.0f}M → ${bi27/1e6:,.0f}M ({(bi27/bi26-1)*100:+.1f}%, n={len(inc)}). Including them understates growth."),
    ])

    # prior years, budget-to-budget (adopted budgets)
    bb = ufb_benefit_budgets()
    ids = {r["district_id"] for r in comp}
    yrs = sorted(bb)
    items = []
    for a_, b_ in zip(yrs, yrs[1:]):
        common = ids & set(bb[a_]) & set(bb[b_])
        x, y = sum(bb[a_][d] for d in common), sum(bb[b_][d] for d in common)
        items.append((f"Adopted budget {a_[:2]}-{a_[2:]} → {b_[:2]}-{b_[2:]}", f"{(y/x-1)*100:+.1f}% (n={len(common)})"))
    items.append(("Note", "adopted-to-adopted, original budgets; the 2026-27 row here uses the original 2025-26 base, so it differs from the revised-base figure above"))
    block("Is 2026-27 new? Benefit budget growth by year (comparable districts)", items)

    # aid
    ws = openpyxl.load_workbook(RAW / "stateaid" / "2627" / "FY27_GBM_District_Details.xlsx", read_only=True, data_only=True).worksheets[0]
    aid_rows = [r for r in ws.iter_rows(min_row=6, values_only=True) if r and isinstance(r[1], (int, float))]
    block("Formula aid (NJDOE FY27 district details)", [
        ("All districts in the aid file", f"{len(aid_rows)}; FY26 ${sum(r[3] for r in aid_rows)/1e9:.3f}B → FY27 ${sum(r[12] for r in aid_rows)/1e9:.3f}B ({(sum(r[12] for r in aid_rows)-sum(r[3] for r in aid_rows))/1e6:+.0f}M)"),
        ("Districts with an aid cut (whole file)", sum(1 for r in aid_rows if r[13] < 0)),
        ("Comparable districts: aid change", f"{aid/1e6:+.0f}M; cuts in {sum(1 for r in comp if f(r['state_aid_change_dollars']) < 0)}"),
        ("Comparable districts where the benefit increase exceeded the aid change",
         f"{sum(1 for r in comp if f(r['aid_change_minus_benefit_change']) < 0)} of {len(comp)}"),
    ])

    # health
    hs = med([f(r["acfr_health_share_of_benefits_2025"]) for r in comp])
    hg = med([f(r["acfr_health_growth_23_25_pct"]) for r in comp])
    hs_r = med([f(r["acfr_health_share_of_benefits_2025"]) for r in comp if r["acfr_quality_2025"] == "reconciled"])
    hg_r = med([f(r["acfr_health_growth_23_25_pct"]) for r in comp
                if r["acfr_quality_2025"] == "reconciled" and r["acfr_quality_2023"] == "reconciled"])
    block("Health (audited ACFRs)", [
        ("Health share of district-paid benefits, FY25 median", f"{hs[0]:.1f}% (n={hs[1]}); reconciled rows only {hs_r[0]:.1f}% (n={hs_r[1]})"),
        ("Audited health growth FY23→FY25, median", f"{hg[0]:+.1f}% (n={hg[1]}); reconciled rows only {hg_r[0]:+.1f}% (n={hg_r[1]})"),
    ])

    # SEHBP, raw and controlled
    def ch(r):
        return f(r["benefits_change_pct"])
    s_ = med([ch(r) for r in comp if r["in_sehbp"] == "True"])
    o_ = med([ch(r) for r in comp if r["in_sehbp"] != "True"])
    diffs = []
    for c in sorted({r["county"] for r in comp}):
        a1 = [ch(r) for r in comp if r["county"] == c and r["in_sehbp"] == "True" and ch(r) is not None]
        a2 = [ch(r) for r in comp if r["county"] == c and r["in_sehbp"] != "True" and ch(r) is not None]
        if len(a1) >= 3 and len(a2) >= 3:
            diffs.append((c, statistics.median(a1) - statistics.median(a2), len(a1), len(a2)))
    sizes = sorted(f(r["benefits_budget_2526"]) for r in comp)
    t1, t2 = sizes[len(sizes)//3], sizes[2*len(sizes)//3]
    tier = lambda r: 0 if f(r["benefits_budget_2526"]) <= t1 else 1 if f(r["benefits_budget_2526"]) <= t2 else 2
    tiers = []
    for t in range(3):
        a1 = med([ch(r) for r in comp if tier(r) == t and r["in_sehbp"] == "True"])
        a2 = med([ch(r) for r in comp if tier(r) == t and r["in_sehbp"] != "True"])
        tiers.append(f"{['small', 'mid', 'large'][t]}: {a1[0]:+.1f}% (n={a1[1]}) vs {a2[0]:+.1f}% (n={a2[1]})")
    block("SEHBP vs. other plans (median budgeted benefit growth; membership name-matched to the Oct 2026 list)", [
        ("Raw", f"SEHBP {s_[0]:+.1f}% (n={s_[1]}) vs other {o_[0]:+.1f}% (n={o_[1]})"),
        ("Within-county gap (counties with ≥3 of each)", "; ".join(f"{c} {d:+.1f} pts ({n1}/{n2})" for c, d, n1, n2 in diffs)
         + (f" → median {statistics.median(d for _, d, _, _ in diffs):+.1f} pts" if diffs else "")),
        ("By district size (benefits budget terciles)", "; ".join(tiers)),
        ("Caveat", "the Oct 2026 list post-dates the budgets; some audits contradict it (validation V6)"),
    ])

    lv = [f(r["levy_change_pct"]) for r in comp if f(r["levy_change_pct"]) is not None]
    fb26, fb27 = ben(comp, "fund_balance_used_2526"), ben(comp, "fund_balance_used_2627")
    block("Levy and reserves (comparable districts; UFB)", [
        ("Median general-fund levy change", f"{statistics.median(lv):+.1f}% (n={len(lv)})"),
        ("Districts above 2%", f"{sum(1 for x in lv if x > 2.05)} of {len(lv)} (cause not identifiable from state files)"),
        ("Budgeted fund balance (UFB line 580, the planned drawdown, not remaining reserves)", f"${fb26/1e6:,.0f}M (2025-26) → ${fb27/1e6:,.0f}M (2026-27)"),
        ("Same, all districts in panel", f"${ben(rows, 'fund_balance_used_2526')/1e6:,.0f}M → ${ben(rows, 'fund_balance_used_2627')/1e6:,.0f}M"),
    ])

    st = [(f(r["students_per_teacher_2021_22"]), f(r["students_per_teacher_2024_25"])) for r in rows]
    st = [(a, b) for a, b in st if a and b]
    block("Students per teacher (TGES Indicator 16 ratio; all districts with both years)", [
        ("Districts", len(st)),
        ("Up by more than 0.2 / down by more than 0.2 / strictly higher", f"{sum(b > a + 0.2 for a, b in st)} / {sum(b < a - 0.2 for a, b in st)} / {sum(b > a for a, b in st)}"),
        ("Median change", f"{statistics.median(b - a for a, b in st):+.2f}"),
        ("Caveat", "students per teaching staff member, about half of typical class size, so not a class-size measure; 2021-22 is actual, 2024-25 is the edition's budget-year column"),
    ])

    # South Jersey (Burlington 05, Camden 07, Gloucester 15)
    sj_all = [r for r in rows if r["county_id"] in ("05", "07", "15")]
    sj = [r for r in comp if r["county_id"] in ("05", "07", "15")]
    s26, s27 = ben(sj, "benefits_budget_2526"), ben(sj, "benefits_budget_2627")
    sa = ben(sj, "state_aid_change_dollars")
    cc = sum(f(r["state_aid_change_dollars"]) or 0 for r in sj if r["district_name"].upper().startswith("CAMDEN CITY"))
    nocc = [r for r in sj if not r["district_name"].upper().startswith("CAMDEN CITY")]
    slv = [f(r["levy_change_pct"]) for r in sj if f(r["levy_change_pct"]) is not None]
    sch = lambda flag: med([f(r["benefits_change_pct"]) for r in sj if (r["in_sehbp"] == "True") == flag])
    block("South Jersey: Burlington, Camden, Gloucester (comparable districts unless noted)", [
        ("Districts", f"{len(sj)} comparable of {len(sj_all)}"),
        ("Benefit increase exceeded aid change", f"{sum(1 for r in sj if f(r['aid_change_minus_benefit_change']) < 0)} of {len(sj)}"),
        ("Employee benefits", f"${s26/1e6:,.1f}M → ${s27/1e6:,.1f}M ({(s27/s26-1)*100:+.1f}%, {(s27-s26)/1e6:+,.1f}M)"),
        ("Formula aid change", f"{sa/1e6:+,.1f}M, of which Camden City {cc/1e6:+,.1f}M"),
        ("Without Camden City", f"aid {(sa-cc)/1e6:+,.1f}M vs benefits {(ben(nocc, 'benefits_budget_2627')-ben(nocc, 'benefits_budget_2526'))/1e6:+,.1f}M"),
        ("Median general-fund levy change", f"{statistics.median(slv):+.1f}%; above 2%: {sum(1 for x in slv if x > 2.05)} of {len(slv)}"),
        ("Budgeted fund balance (planned drawdown)", f"${ben(sj, 'fund_balance_used_2526')/1e6:,.0f}M → ${ben(sj, 'fund_balance_used_2627')/1e6:,.0f}M"),
        ("Health share of district-paid benefits, FY25 median", "{:.1f}% (n={})".format(*med([f(r["acfr_health_share_of_benefits_2025"]) for r in sj]))),
        ("Audited health growth FY23→FY25, median", "{:+.1f}% (n={})".format(*med([f(r["acfr_health_growth_23_25_pct"]) for r in sj]))),
        ("Median budgeted benefit growth, SEHBP vs other", "{:+.1f}% (n={}) vs ".format(*sch(True)) + "{:+.1f}% (n={})".format(*sch(False))),
    ])
    out = ROOT / "docs" / "findings" / "numbers.md"
    out.write_text("\n".join(L))
    print(out.read_text())


if __name__ == "__main__":
    main()
