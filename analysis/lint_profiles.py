#!/usr/bin/env python3
"""Consistency checks for research/districts/*/*.md; writes docs/profile-lint.md.

  L1  Assessment/Confidence figures ($ amounts, percentages) that appear nowhere else in the profile:
      usually stale numbers left over from an earlier baseline. Each needs a source in the profile body or removal.
  L2  Confidence heading vs facts-line confidence disagree.
  L3  Missing classification, confidence or facts line.
  L4  Confirmed/Consistent profile rated Low (shouldn't be cited), or Confirmed with no positions/class-size evidence.

    .venv/bin/python analysis/lint_profiles.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "research" / "districts"
CLASSES = ["Confirmed", "Consistent", "No cuts reported", "Insufficient evidence"]
FIG = re.compile(r"[-+]?\$\d[\d,]*(?:\.\d+)?\s?[MK]?\b|[-+]?\d+(?:\.\d+)?%")


def norm(x):
    """'$2.36M' / '$2,360,000' / '+12.1%' → comparable canonical forms."""
    s = x.replace(" ", "").lstrip("+-")
    if s.endswith("%"):
        v = float(s[:-1])
        return {f"{v:.1f}%", f"{round(v)}%"} if "." in s else {f"{round(v)}%"}
    v = float(re.sub(r"[$,MK]", "", s)) * (1e6 if s.endswith("M") else 1e3 if s.endswith("K") else 1)
    return {f"{v/1e6:.2f}M", f"{v/1e6:.1f}M", f"{round(v/1e3)}K", f"{round(v)}"}


def section(t, head):
    m = re.search(rf"^## {head}\s*\n(.*?)(?=^## |<!-- facts|\Z)", t, re.S | re.M)
    return m.group(1) if m else ""


def main():
    issues = []
    for p in sorted(DIR.glob("*/*.md")):
        if p.name == "README.md":
            continue
        t = p.read_text()
        rel = p.relative_to(DIR)
        judged = section(t, "Assessment") + section(t, "Confidence")
        rest = t.replace(section(t, "Assessment"), "").replace(section(t, "Confidence"), "")
        known = set()
        for x in FIG.findall(rest) + ["$" + n for n in re.findall(r"(?<![\d$.,])\d{1,3}(?:,\d{3})+(?![\d,])", rest)]:
            known |= norm(x)  # also bare numbers like "4,220,162" quoted from slides

        def shown(m):
            """Computed figure with its inputs written next to it, e.g. "+$1.15M ($6.85M − $5.70M)" or "43% = a ÷ b"."""
            near = re.split(r"\.\s", judged[m.end(): m.end() + 100])[0]  # rest of the sentence
            return bool(re.search(r"[(:=][^)\n]*\d[^)\n]*(?:[−→÷×]| \+ )[^)\n]*\d", near))
        stale = sorted({m.group(0).strip() for m in FIG.finditer(judged)
                        if not (norm(m.group(0)) & known) and not shown(m)
                        and m.group(0).strip().lstrip("+-") not in ("2%", "100%")})  # 2% = statutory cap
        if stale:
            issues.append((rel, "L1", "not found elsewhere in profile: " + ", ".join(stale)))
        lead = re.match(r"\s*\*\*(" + "|".join(CLASSES) + r")\b", section(t, "Assessment"))
        cls = lead.group(1) if lead else None  # the label must open the Assessment
        conf = re.match(r"\s*\**(High|Medium|Low)", section(t, "Confidence"), re.I)
        facts = re.search(r"<!-- facts: (.*?) -->", t, re.S)
        fconf = re.search(r"confidence=(\w+)", facts.group(1)) if facts else None
        if not cls or not conf or not facts:
            issues.append((rel, "L3", f"classification={cls} confidence={conf and conf.group(1)} facts={'yes' if facts else 'no'}"))
        if conf and fconf and conf.group(1).lower() != fconf.group(1).lower():
            issues.append((rel, "L2", f"heading {conf.group(1)} vs facts {fconf.group(1)}"))
        if cls in ("Confirmed", "Consistent") and conf and conf.group(1).lower() == "low":
            issues.append((rel, "L4", f"{cls} at Low confidence: do not cite as an example"))
        if cls == "Confirmed" and facts and "positions_cut=unknown" in facts.group(1) and "class_size_increase=yes" not in facts.group(1):
            issues.append((rel, "L4", "Confirmed but no documented positions cut or class-size increase"))
    out = ["# Profile lint", "",
           "_Generated by `analysis/lint_profiles.py`. L1 lists Assessment/Confidence figures that don't appear anywhere else "
           "in the same profile (Our numbers, sourced bullets, verification), which usually means a stale or unsourced number; "
           "rounded restatements of a sourced figure can also show up and are harmless. Computed figures followed by their inputs (\"+$1.15M ($6.85M − $5.70M)\") are not flagged._", "",
           f"{len(issues)} issues in {len({i[0] for i in issues})} profiles.", "",
           "| Profile | Check | Detail |", "|---|---|---|"]
    out += [f"| [{r}](../research/districts/{r}) | {c} | {d.replace('|', '/')} |" for r, c, d in issues]
    (ROOT / "docs" / "profile-lint.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/profile-lint.md: {len(issues)} issues")


if __name__ == "__main__":
    main()
