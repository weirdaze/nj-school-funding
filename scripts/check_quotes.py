#!/usr/bin/env python3
"""Check that quoted text in profile source bullets appears word for word in the cited document; write docs/quote-check.md.

For each quoted string (12+ characters) in the "What the district / local reporting says" bullets, every URL on the
same line is fetched (cached under data/raw/quote_cache) and searched, ignoring case, punctuation and markdown bold;
"…" splits a quote into pieces that must all appear. Status classes:
  verbatim     found in a cited document
  not found    the document was read but the quote isn't in its text: a paraphrase, a quote from another source,
               or text the extractor can't see (image slides, .pptx, scripted pages); check by hand
  unfetchable  no cited document could be fetched (paywall, bot wall, dead link)
  no link      the line cites no URL (usually "same presentation" bullets)

    .venv/bin/python scripts/check_quotes.py
"""
import hashlib
import html
import re
import subprocess
import unicodedata
from collections import Counter
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "data" / "raw" / "quote_cache"
QUOTE = re.compile(r'["“]([^"”]{12,400})["”]')
LINK = re.compile(r"\]\((https?://[^)\s]+)\)")


def toks(s):
    s = unicodedata.normalize("NFKC", html.unescape(s)).replace("**", "").lower()
    s = re.sub(r"\[[^\]]*\]", " ", s)  # editorial insertions
    return re.sub(r"[^a-z0-9$%]+", " ", s).split()


def fetch(url):
    url = url.split("#")[0]
    f = CACHE / hashlib.sha1(url.encode()).hexdigest()
    code = CACHE / (f.name + ".code")
    if not code.exists():
        r = subprocess.run(["curl", "-sL", "--compressed", "--max-time", "40", "-A", "Mozilla/5.0 (Macintosh) Safari/605",
                            "-o", str(f), "-w", "%{http_code}", url], capture_output=True, text=True)
        code.write_text(r.stdout or "000")
    if not code.read_text().startswith("2") or not f.exists():
        return None
    b = f.read_bytes()
    if b[:4] == b"%PDF":
        try:
            t = " ".join(p.get_text() for p in pymupdf.open(stream=b, filetype="pdf"))
        except Exception:
            return None
    else:
        t = re.sub(r"<[^>]+>", " ", re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", " ", b.decode("utf-8", "ignore")))
    return " " + " ".join(toks(t)) + " "


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    rows = []
    for p in sorted((ROOT / "research" / "districts").glob("*/*.md")):
        sec = re.search(r"^## What the district.*?(?=^## )", p.read_text(), re.S | re.M)
        for line in (sec.group(0).splitlines() if sec else []):
            if not line.startswith("- ["):
                continue
            urls = LINK.findall(line)
            for q in QUOTE.findall(line):
                if q != q.strip() or len(q.split()) < 3:
                    continue  # a fragment between two quotations, not a quotation
                parts = [" " + " ".join(toks(x)) + " " for x in re.split(r"\s*(?:…|\.\.\.)\s*", q) if len(toks(x)) >= 2]
                texts = [t for t in map(fetch, urls) if t]
                status = ("no link" if not urls else "unfetchable" if not texts
                          else "verbatim" if any(all(x in t for x in parts) for t in texts) else "not found")
                rows.append((p.relative_to(ROOT / "research" / "districts"), status, q))
    c = Counter(r[1] for r in rows)
    out = ["# Quote check", "", "_Generated by `scripts/check_quotes.py`. A \"not found\" is not necessarily wrong: image-only "
           "slides, .pptx decks and scripted pages yield no text, and some lines quote a second source. The 2026-10-25 run was "
           "triaged by hand: three paraphrases in quotation marks were fixed (Cherry Hill, Collingswood, Piscataway) and a "
           "headline corrected (Pleasantville); the rest come from documents the script can't read or quote a second "
           "document, and the script has not verified them._", "",
           ", ".join(f"{k}: {c[k]}" for k in ("verbatim", "not found", "unfetchable", "no link")), "",
           "| Profile | Status | Quote |", "|---|---|---|"]
    out += [f"| [{r}](../research/districts/{r}) | {s} | {q[:160].replace('|', '/')} |" for r, s, q in rows if s != "verbatim"]
    (ROOT / "docs" / "quote-check.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/quote-check.md: {dict(c)}")


if __name__ == "__main__":
    main()
